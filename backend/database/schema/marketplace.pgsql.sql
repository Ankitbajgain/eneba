-- PostgreSQL marketplace domain schema, applied by the versioned migration.
-- IDs use identity sequences; timestamps are UTC without time zone.

CREATE TABLE sellers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(120) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  rating_hundredths INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  CHECK (rating_hundredths BETWEEN 0 AND 500)
);

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(180) NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  cover_url VARCHAR(2048) NOT NULL,
  release_date DATE NULL,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE platforms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL
);

CREATE TABLE regions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  activation_note TEXT NOT NULL
);

CREATE TABLE offers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  seller_id BIGINT NOT NULL,
  platform_id BIGINT NOT NULL,
  region_id BIGINT NOT NULL,
  price_minor INTEGER NOT NULL,
  reference_price_minor INTEGER NULL,
  currency CHAR(3) NOT NULL DEFAULT 'EUR',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  CONSTRAINT offers_identity UNIQUE (product_id, seller_id, platform_id, region_id),
  FOREIGN KEY (product_id) REFERENCES products(id),
  FOREIGN KEY (seller_id) REFERENCES sellers(id),
  FOREIGN KEY (platform_id) REFERENCES platforms(id),
  FOREIGN KEY (region_id) REFERENCES regions(id),
  CHECK (price_minor BETWEEN 1 AND 10000000),
  CHECK (reference_price_minor IS NULL OR reference_price_minor >= price_minor),
  CHECK (currency = 'EUR')
);

CREATE TABLE carts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE,
  revision BIGINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id),
  CHECK (revision >= 1)
);

CREATE TABLE cart_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_id BIGINT NOT NULL,
  offer_id BIGINT NOT NULL,
  quantity INTEGER NOT NULL,
  observed_price_minor INTEGER NOT NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  CONSTRAINT cart_offer UNIQUE (cart_id, offer_id),
  FOREIGN KEY (cart_id) REFERENCES carts(id) ON DELETE CASCADE,
  FOREIGN KEY (offer_id) REFERENCES offers(id),
  CHECK (quantity BETWEEN 1 AND 10),
  CHECK (observed_price_minor BETWEEN 1 AND 10000000)
);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id CHAR(36) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'EUR',
  total_minor BIGINT NOT NULL,
  idempotency_key CHAR(36) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  fulfilled_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  CONSTRAINT order_idempotency UNIQUE (user_id, idempotency_key),
  FOREIGN KEY (user_id) REFERENCES users(id),
  CHECK (status IN ('fulfilled', 'failed')),
  CHECK (currency = 'EUR'),
  CHECK (total_minor > 0),
  CHECK ((status = 'fulfilled' AND fulfilled_at IS NOT NULL)
      OR (status = 'failed' AND fulfilled_at IS NULL))
);

CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  offer_id BIGINT NOT NULL,
  product_title VARCHAR(255) NOT NULL,
  seller_name VARCHAR(120) NOT NULL,
  platform_name VARCHAR(100) NOT NULL,
  region_name VARCHAR(100) NOT NULL,
  quantity INTEGER NOT NULL,
  unit_price_minor INTEGER NOT NULL,
  line_total_minor BIGINT NOT NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(id),
  FOREIGN KEY (offer_id) REFERENCES offers(id),
  CHECK (quantity BETWEEN 1 AND 10),
  CHECK (unit_price_minor BETWEEN 1 AND 10000000),
  CHECK (line_total_minor = quantity * unit_price_minor)
);

CREATE TABLE digital_keys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offer_id BIGINT NOT NULL,
  encrypted_value TEXT NOT NULL,
  fingerprint CHAR(64) NOT NULL UNIQUE,
  order_item_id BIGINT NULL,
  sold_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  FOREIGN KEY (offer_id) REFERENCES offers(id),
  FOREIGN KEY (order_item_id) REFERENCES order_items(id),
  CHECK ((order_item_id IS NULL AND sold_at IS NULL)
      OR (order_item_id IS NOT NULL AND sold_at IS NOT NULL))
);

CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE,
  provider VARCHAR(30) NOT NULL DEFAULT 'simulated',
  reference CHAR(36) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL,
  amount_minor BIGINT NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'EUR',
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(id),
  CHECK (provider = 'simulated'),
  CHECK (status IN ('succeeded', 'declined')),
  CHECK (amount_minor > 0),
  CHECK (currency = 'EUR')
);

CREATE TABLE homepage_blocks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  block_key VARCHAR(80) NOT NULL UNIQUE,
  type VARCHAR(30) NOT NULL,
  title VARCHAR(150) NOT NULL,
  position INTEGER NOT NULL,
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  starts_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  ends_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  CHECK (type IN ('banner', 'best_sellers', 'deals')),
  CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at),
  CHECK (position BETWEEN 0 AND 65535)
);

CREATE TABLE banners (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  homepage_block_id BIGINT NOT NULL,
  heading VARCHAR(150) NOT NULL,
  subheading VARCHAR(255) NULL,
  image_url VARCHAR(2048) NOT NULL,
  target_path VARCHAR(255) NOT NULL,
  cta_label VARCHAR(80) NOT NULL,
  position INTEGER NOT NULL,
  starts_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  ends_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  FOREIGN KEY (homepage_block_id) REFERENCES homepage_blocks(id),
  CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at),
  CHECK (position BETWEEN 0 AND 65535)
);

CREATE TABLE product_search_grams (
  gram VARCHAR(3) NOT NULL,
  product_id BIGINT NOT NULL,
  PRIMARY KEY (gram, product_id),
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE INDEX products_public_title ON products (is_published, title, id);
CREATE INDEX offers_filter ON offers (is_active, platform_id, region_id, price_minor, product_id);
CREATE INDEX offers_product_price ON offers (product_id, is_active, price_minor);
CREATE INDEX orders_history ON orders (user_id, created_at, id);
CREATE INDEX orders_bestsellers ON orders (status, fulfilled_at, id);
CREATE INDEX keys_inventory ON digital_keys (offer_id, order_item_id, id);
CREATE INDEX homepage_order ON homepage_blocks (is_enabled, position, id);
CREATE INDEX banners_block ON banners (homepage_block_id, position, id);
CREATE INDEX grams_product ON product_search_grams (product_id);
